# 1. Create a list of numbers from 1 to 10
numbers = list(range(1, 11))

# 2. Extract the first five elements from the list
first_five_elements = numbers[:5]

# 3. Reverse these extracted elements
reversed_elements = first_five_elements[::-1]

# 4. Print both the extracted list and the reversed list
print("Extracted List (First five elements):", first_five_elements)
print("Reversed List:", reversed_elements)
